    // Public Methods
    // =========================================================================

    /**
     * The commit-msg hook: rejects a message that carries AI attribution, naming
     * the line, and never human collaboration. Comment lines are ignored.
     *
     * Rejected, case-insensitively: a Co-Authored-By trailer (any leading
     * whitespace) naming an AI tool or an AI vendor address; "Generated with",
     * "Generated by" or a Generated-by trailer followed by an AI tool; an
     * Assisted-by trailer naming an AI tool; a Claude-Session line; the robot
     * emoji footer. A human Co-authored-by trailer, "generated with Faker" or
     * "generated by hand" pass. In a Co-Authored-By trailer (with or without a
     * space after the colon), tool words that are also people's names (Claude,
     * Devin, Gemini, Cursor, Copilot, OpenAI) count only with an AI qualifier or
     * the vendor's address ("Claude Sonnet", "Gemini Code Assist", "Cursor Agent",
     * "GitHub Copilot", noreply@anthropic.com). A tool name wrapped in markdown
     * ("Generated with [Claude Code](...)") still counts.
     *
     * @author michtio
     */
    public static function commitMsg(): string
    {
        return <<<'SH'
#!/bin/sh
# Written by claude-skills:setup. Rejects a commit message that carries AI
# attribution: a Co-Authored-By trailer naming an AI tool or vendor, "Generated
# with/by <AI tool>", an Assisted-by trailer naming an AI tool, a Claude-Session
# line, or the robot emoji footer. Human Co-authored-by trailers pass. Lines
# starting with # are ignored.
# Active once `git config core.hooksPath .githooks` is set.

message_file=$1

# Word edges: not a letter or digit (or the start or end of the line).
l='(^|[^[:alnum:]])'
r='([^[:alnum:]]|$)'

# AI tools and vendors, for "Generated with/by" and Assisted-by lines.
tools='claude|anthropic|copilot|chatgpt|openai|codex|gpt|cursor|cursoragent|gemini|bard|devin|aider|windsurf|codeium|tabnine|codewhisperer|llm|ai'

# In a co-author trailer a tool word that is also a person's name (Claude,
# Devin, Gemini, Cursor, Copilot, OpenAI) counts only with an AI qualifier.
coauthors='claude[[:space:]]+(opus|sonnet|haiku|fable|code|instant|[0-9])|claude\[bot\]|github[[:space:]]+copilot|copilot\[bot\]|chatgpt|openai[[:space:]]+(codex|chatgpt|gpt|agent|assistant)|codex|gpt|gemini[[:space:]]+(code[[:space:]]+assist|cli|pro|flash|ultra|agent|[0-9])|gemini\[bot\]|cursor[[:space:]]+(agent|ai|bot)|cursoragent|cursor\[bot\]|devin[[:space:]-]*ai|devin\[bot\]|aider|windsurf|codeium|tabnine|codewhisperer'

# Or an AI vendor's own address (Copilot with a github.com address, Gemini with
# a google.com one).
addresses='@(anthropic\.com|openai\.com|cognition\.ai|cursor\.com|aider\.chat)([^[:alnum:].-]|$)|copilot.*@(users\.noreply\.)?github\.com|gemini.*@google\.com'

# Markdown that may wrap the tool name: [Claude Code](...), *Copilot*, `codex`.
md='[][(*_`]*'

robot=$(printf '\360\237\244\226')

found=$(grep -v '^#' "$message_file" | grep -i -E \
    -e "^[[:space:]]*co-authored-by:(.*[^[:alnum:]])?($coauthors)$r" \
    -e "^[[:space:]]*co-authored-by:.*($addresses)" \
    -e "^[[:space:]]*assisted-by:(.*[^[:alnum:]])?($tools)$r" \
    -e "${l}generated(-by:|[[:space:]]+(with|by))[[:space:]]+((a|an|the)[[:space:]]+)?$md(github[[:space:]]+|google[[:space:]]+|openai[[:space:]]+)?($tools)$r" \
    -e '^[[:space:]]*claude-session:' \
    -e "$robot.*generated" \
    | head -n 1)

if [ -n "$found" ]; then
    echo "commit-msg: remove this AI attribution line from the commit message: $found" >&2
    exit 1
fi

exit 0

SH;
    }

    /**
     * The DDEV web image addition: installs the gitleaks release the CI workflow
     * pins, the archive chosen by DDEV's `$TARGETARCH` and checked against
     * gitleaks' own checksums, so the local scan is the CI scan. DDEV merges
     * `.ddev/web-build/Dockerfile.*` into the web image; `ddev restart` builds it.
     * Proven by tests/Profile/S9d1GitleaksTest.php ("plans a pinned gitleaks install
     * into the DDEV web image"); the real build runs in tests/gate/test_s9b_ddev.py.
     *
     * @author michtio
     */
    public static function gitleaksDockerfile(): string
    {
        $version = WorkflowPlanner::GITLEAKS_VERSION;
        $x64 = WorkflowPlanner::GITLEAKS_SHA256;
        $arm64 = self::GITLEAKS_SHA256_ARM64;

        return <<<DOCKER
# Written by claude-skills:setup. Installs gitleaks {$version}, the release the
# CI workflow pins, into the DDEV web image, so the secret scan of
# `composer test` runs the same locally as in CI. `ddev restart` builds it.
# The checksums are gitleaks' own (gitleaks_{$version}_checksums.txt).
RUN set -eu; \
    case "\${TARGETARCH}" in \
        amd64) arch=x64; sum={$x64} ;; \
        arm64) arch=arm64; sum={$arm64} ;; \
        *) echo "gitleaks: no pinned archive for \${TARGETARCH}" >&2; exit 1 ;; \
    esac; \
    archive="gitleaks_{$version}_linux_\${arch}.tar.gz"; \
    cd /tmp; \
    curl -sSfL --retry 3 --proto '=https' --tlsv1.2 -o "\${archive}" "https://github.com/gitleaks/gitleaks/releases/download/v{$version}/\${archive}"; \
    echo "\${sum}  \${archive}" | sha256sum -c -; \
    tar -xzf "\${archive}" --no-same-owner -C /usr/local/bin gitleaks; \
    rm -f "\${archive}"

DOCKER;
    }

    /**
     * The secret scan step: gitleaks with the project config. Without gitleaks it
     * skips with a message on the host, and fails in CI and inside DDEV
     * (`IS_DDEV_PROJECT=true`) when `.ddev/web-build/Dockerfile.gitleaks` exists,
     * the image addition the setup writes for the DDEV runner; inside DDEV without
     * it (a project set to the host runner) it skips like the host. Proven by
     * tests/Profile/S9d1GitleaksTest.php ("fails the secret scan inside DDEV when
     * gitleaks is missing", "still skips ... on the host") and
     * tests/Profile/SecretScanTest.php.
     *
     * @author michtio
     */
    public static function gitleaksCheck(): string
    {
        return <<<'SH'
#!/bin/sh
# Written by claude-skills:setup. The secret scan step of `composer test`.
# Runs gitleaks with .gitleaks.toml. Without gitleaks it skips on the host and
# fails in CI (the CI variable set), and inside DDEV when the setup's web image
# addition (.ddev/web-build/Dockerfile.<tool>) exists, so neither passes without
# the scan.

if command -v gitleaks >/dev/null 2>&1; then
    exec gitleaks detect --source . --config .gitleaks.toml --no-banner
fi

if [ -n "${CI:-}" ]; then
    echo "gitleaks is required in CI: install it before running composer test" >&2
    exit 1
fi

tool=gitleaks

if [ "${IS_DDEV_PROJECT:-}" = "true" ] && [ -f ".ddev/web-build/Dockerfile.${tool}" ]; then
    echo "gitleaks is missing in the DDEV web container: run ddev restart to rebuild the web image with it" >&2
    exit 1
fi

echo "gitleaks not found, skipping the secret scan (install gitleaks to run it locally)"
exit 0

SH;
    }

    /**
     * The gitleaks configuration: the default rules plus allowlisted fixture paths,
     * in the `[[allowlists]]` form of gitleaks 8.25.0 and later.
     *
     * @author michtio
     */
    public static function gitleaksConfig(): string
    {
        return <<<'TOML'
# Written by claude-skills:setup. Gitleaks' default rules, with test fixtures and
# the example environment file allowlisted (their values are placeholders).
title = "claude-skills"

[extend]
useDefault = true

# [[allowlists]] needs gitleaks 8.25.0 or later (it replaced [allowlist]).
[[allowlists]]
description = "Test fixtures and example environment values"
paths = [
    '''(^|/)tests/Fixtures/''',
    '''(^|/)\.env\.example$''',
]

TOML;
    }
}
